export function mulberry32(a: number) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Builds one letter pool per ring. Each pool contains the correct letter
 * plus random distractors, shuffled with a seeded RNG so retries reshuffle.
 */
export function buildPools(riddle: RiddleDef, seedBase: number, attempt: number): string[][] {
  const n = riddle.answer.length;
  const size = n <= 3 ? 12 : n <= 5 ? 13 : 14;
  return riddle.answer.map((correct, i) => {
    const rng = mulberry32(seedBase * 7919 + attempt * 1301 + i * 97 + 11);
    const pool = [correct];
    while (pool.length < size) {
      const c = ARABIC_LETTERS[Math.floor(rng() * ARABIC_LETTERS.length)];
      if (!pool.includes(c)) pool.push(c);
    }
    for (let k = pool.length - 1; k > 0; k--) {
      const j = Math.floor(rng() * (k + 1));
      [pool[k], pool[j]] = [pool[j], pool[k]];
    }
    return pool;
  });
}

